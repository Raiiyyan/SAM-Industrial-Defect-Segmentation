def _run_unit_tests():
    """Run synthetic tests for each parser function and generate_box_prompt.
    Exits with code 1 if any test fails.  Uses no real data files —
    all test inputs are created in-memory or in a temp directory.
    """
    import tempfile
    import unittest

    class TestParsers(unittest.TestCase):

        # ── parse_png_mask ──────────────────────────────────────────

        def test_parse_png_mask_binary(self):
            """Synthetic 50x100 PNG with a rectangular defect in top-left."""
            h, w = 100, 200
            mask_np = np.zeros((h, w), dtype=np.uint8)
            mask_np[10:40, 5:35] = 255
            with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
                cv2.imwrite(f.name, mask_np)
                result = parse_png_mask(f.name, target_size=(1024, 1024))
            os.unlink(f.name)
            self.assertEqual(result.shape, (1, 1024, 1024))
            self.assertEqual(result.dtype, torch.float32)
            self.assertTrue((result >= 0).all() and (result <= 1).all())
            # The defect region should survive letterboxing (non-zero somewhere)
            self.assertGreater(
                result.sum().item(),
                0,
                "parse_png_mask: defect region lost after resize",
            )

        def test_parse_png_mask_all_zero(self):
            """All-zero mask (no defect)."""
            h, w = 100, 200
            mask_np = np.zeros((h, w), dtype=np.uint8)
            with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
                cv2.imwrite(f.name, mask_np)
                result = parse_png_mask(f.name, target_size=(1024, 1024))
            os.unlink(f.name)
            self.assertEqual(result.shape, (1, 1024, 1024))
            self.assertEqual(
                result.sum().item(),
                0,
                "parse_png_mask: all-zero mask should remain zero",
            )

        # ── parse_rle_mask ──────────────────────────────────────────

        def test_parse_rle_mask_single_run(self):
            """Single RLE run covering the first 100 pixels of a 200x300 image."""
            h, w = 300, 200
            rle = "1 100"  # pixels 1..100 (1-indexed)
            result = parse_rle_mask(rle, h, w, target_size=(1024, 1024))
            self.assertEqual(result.shape, (1, 1024, 1024))
            self.assertGreater(result.sum().item(), 0)

        def test_parse_rle_mask_two_runs(self):
            """Two disjoint RLE runs."""
            h, w = 10, 10
            # Row 0: pixels 1..3, Row 9: pixels 90..92
            rle = "1 3  90 3"
            result = parse_rle_mask(rle, h, w, target_size=(1024, 1024))
            self.assertEqual(result.shape, (1, 1024, 1024))
            self.assertGreater(result.sum().item(), 0)

        def test_parse_rle_mask_empty(self):
            """Empty RLE string (no defect)."""
            result = parse_rle_mask("", 100, 200, target_size=(1024, 1024))
            self.assertEqual(result.sum().item(), 0)

        def test_parse_rle_mask_malformed(self):
            """Odd number of tokens should raise ValueError."""
            with self.assertRaises(ValueError):
                parse_rle_mask("1 2 3", 100, 100, target_size=(1024, 1024))

        # ── parse_ellipse_mask ───────────────────────────────────────

        def test_parse_ellipse_mask_with_defect(self):
            """Synthetic label PNG with a filled ellipse."""
            h, w = 200, 200
            mask_np = np.zeros((h, w), dtype=np.uint8)
            cv2.ellipse(mask_np, (100, 100), (50, 30), 0, 0, 360, 255, -1)
            with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
                cv2.imwrite(f.name, mask_np)
                result = parse_ellipse_mask(f.name, target_size=(1024, 1024))
            os.unlink(f.name)
            self.assertEqual(result.shape, (1, 1024, 1024))
            self.assertGreater(result.sum().item(), 0)

        def test_parse_ellipse_mask_empty(self):
            """No ellipse — all-zero label."""
            mask_np = np.zeros((100, 100), dtype=np.uint8)
            with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
                cv2.imwrite(f.name, mask_np)
                result = parse_ellipse_mask(f.name, target_size=(1024, 1024))
            os.unlink(f.name)
            self.assertEqual(result.sum().item(), 0)

        # ── parse_bbox_mask ──────────────────────────────────────────

        def test_parse_bbox_mask_rectangle(self):
            """Bounding box in a 200x200 image should produce a rectangular mask."""
            h, w = 200, 200
            bbox = (20, 30, 80, 90)
            result = parse_bbox_mask(bbox, h, w, target_size=(1024, 1024))
            self.assertEqual(result.shape, (1, 1024, 1024))
            self.assertGreater(result.sum().item(), 0)

        def test_parse_bbox_mask_clamped(self):
            """Bounding box extending beyond image edge gets clamped."""
            h, w = 100, 100
            bbox = (-10, -20, 200, 200)
            result = parse_bbox_mask(bbox, h, w, target_size=(1024, 1024))
            self.assertEqual(result.shape, (1, 1024, 1024))
            self.assertGreater(result.sum().item(), 0)

        # ── generate_box_prompt ──────────────────────────────────────

        def test_generate_box_prompt_with_defect(self):
            """Mask with a defect in top-left returns a padded box."""
            mask = torch.zeros((1, 100, 100))
            mask[0, 10:30, 5:25] = 1.0
            box = generate_box_prompt(mask, padding=0.10)
            self.assertEqual(box.shape, (4,))
            self.assertEqual(box.dtype, torch.int64)
            # Box should be inside image bounds
            self.assertGreaterEqual(box[0].item(), 0)
            self.assertGreaterEqual(box[1].item(), 0)
            self.assertLessEqual(box[2].item(), 99)
            self.assertLessEqual(box[3].item(), 99)
            # Padded box should be larger than tight box
            tight_x1, tight_y1 = 5, 10
            self.assertLessEqual(box[0].item(), tight_x1)
            self.assertLessEqual(box[1].item(), tight_y1)

        def test_generate_box_prompt_no_defect(self):
            """All-zero mask returns zero box."""
            mask = torch.zeros((1, 100, 100))
            box = generate_box_prompt(mask, padding=0.10)
            self.assertTrue((box == 0).all().item())

        def test_generate_box_prompt_touches_border(self):
            """Defect touching image edge — box should be clipped, not out-of-bounds."""
            mask = torch.zeros((1, 50, 50))
            mask[0, 0:10, 0:10] = 1.0
            box = generate_box_prompt(mask, padding=0.10)
            self.assertGreaterEqual(box[0].item(), 0)
            self.assertGreaterEqual(box[1].item(), 0)

    suite = unittest.TestLoader().loadTestsFromTestCase(TestParsers)
    runner = unittest.TextTestRunner(verbosity=2)
    result = runner.run(suite)
    if not result.wasSuccessful():
        exit(1)


