# 2. BOX PROMPT GENERATION
# ===================================================================


def generate_box_prompt(mask: torch.Tensor, padding: float = 0.1) -> torch.Tensor:
    """Generate a bounding-box prompt from a binary ground-truth mask.

    The box is expanded by *padding* (fraction of box size) in each direction,
    then clipped to image bounds.  If the mask is all-zero (no defect), returns
    a zero-filled box ``[0, 0, 0, 0]`` — SAM treats an empty box as "segment
    the whole image".

    Parameters
    ----------
    mask : torch.Tensor  shape (1, H, W) float32, values 0 or 1.
    padding : float  fractional expansion (default 0.10 = 10 %).

    Returns
    -------
    torch.Tensor  shape (4,) = [x1, y1, x2, y2]  (integer coordinates).
    """
    H, W = mask.shape[1:]
    indices = torch.nonzero(mask.squeeze(0))
    if indices.numel() == 0:
        return torch.zeros(4, dtype=torch.int64)

    y1 = indices[:, 0].min().item()
    y2 = indices[:, 0].max().item()
    x1 = indices[:, 1].min().item()
    x2 = indices[:, 1].max().item()

    box_h = y2 - y1
    box_w = x2 - x1
    pad_y = int(round(box_h * padding))
    pad_x = int(round(box_w * padding))

    x1 = max(0, x1 - pad_x)
    y1 = max(0, y1 - pad_y)
    x2 = min(W - 1, x2 + pad_x)
    y2 = min(H - 1, y2 + pad_y)

    return torch.tensor([x1, y1, x2, y2], dtype=torch.int64)


