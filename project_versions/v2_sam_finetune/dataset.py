# ── Dataset registry ────────────────────────────────────────────────
SUPPORTED_DATASETS = (
    "mvtec_ad",
    "mvtec_ad_2",
    "severstal",
    "neu_det",
    "dagm2007",
    "defect_spectrum",
)


class UniversalIndustrialDataset(Dataset):
    """Unified Dataset that loads samples from one of six industrial-defect
    datasets and returns standardised tensors ready for SAM fine-tuning.

    Parameters
    ----------
    root_dir : str
        Path to the *parent* directory containing all dataset folders.
        Expected folder names inside *root_dir*:

        =====================  =============================================
        ``dataset_name``       Expected subdirectory
        =====================  =============================================
        ``mvtec_ad``           ``MVTec AD/``
        ``mvtec_ad_2``         ``mvtec_ad_2/``
        ``severstal``          ``severstal-steel-defect-detection/``
        ``neu_det``            ``NEU-DET/``
        ``dagm2007``           ``DAGM_KaggleUpload/``
        ``defect_spectrum``    ``Hug/``
        =====================  =============================================

    dataset_name : str  one of SUPPORTED_DATASETS.
    split : str  ``"train"``, ``"val"``, or ``"test"``.
    target_size : (W, H)  default (1024, 1024).
    transform : callable or None  applied *after* letterbox + normalisation.
    """

    def __init__(
        self,
        root_dir: str,
        dataset_name: str,
        split: str = "train",
        target_size: Tuple[int, int] = TARGET_SIZE,
        transform: Optional[Callable] = None,
        use_cache: bool = False,
    ):
        if dataset_name not in SUPPORTED_DATASETS:
            raise ValueError(
                f"Unknown dataset '{dataset_name}'.  Choose from {SUPPORTED_DATASETS}"
            )
        self.root_dir = root_dir
        self.dataset_name = dataset_name
        self.split = split
        self.target_size = target_size
        self.transform = transform
        self.use_cache = use_cache

        # Path shortcuts
        self._root_dir = root_dir

        # Build sample list
        loader = getattr(self, f"_load_{dataset_name}")
        all_samples = loader()  # list of dicts
        self.samples = self._filter_split(all_samples, split)

        if len(self.samples) == 0:
            logger.warning(
                "UniversalIndustrialDataset(%s, %s) — 0 samples!",
                dataset_name,
                split,
            )

        # ImageNet normalisation (applied after letterbox)
        self.normalize = transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD)
        self.to_tensor = transforms.ToTensor()  # HWC uint8 → CHW float [0,1]

        # Precomputed cache (populated by precompute_cache())
        self._image_cache: Optional[Dict[int, torch.Tensor]] = None
        self._mask_cache: Optional[Dict[int, torch.Tensor]] = None

    def __len__(self) -> int:
        return len(self.samples)

    def precompute_cache(self):
        """Load all images and masks into RAM so __getitem__ is instant.

        Call this BEFORE creating the DataLoader.  Eliminates disk I/O
        during training — critical for GPU utilization on small VRAM cards.
        """
        self._image_cache = {}
        self._mask_cache = {}
        for i in range(len(self.samples)):
            sample = self.samples[i]
            self._image_cache[i] = self._load_image(sample["image_path"])
            self._mask_cache[i] = self._load_mask(sample)
        self.use_cache = True
        logger.info(
            "Cached %d images + masks for %s/%s",
            len(self.samples),
            self.dataset_name,
            self.split,
        )

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """Return a dict with keys:

        - ``image``        : (3, H, W)  float32  ImageNet-normalised, letterboxed.
        - ``mask``         : (1, H, W)  float32  binary.
        - ``box_prompt``   : (4,)       int64   [x1, y1, x2, y2].
        - ``class_label``  : int        per-dataset class index.
        - ``source_dataset`` : str      dataset_name.
        - ``meta``          : dict      sample metadata (used for label mapping).
        """
        sample = self.samples[idx]
        if self.use_cache and self._image_cache is not None:
            img = self._image_cache[idx]
            mask = self._mask_cache[idx]
        else:
            img = self._load_image(sample["image_path"])
            mask = self._load_mask(sample)
        box = generate_box_prompt(mask, padding=0.10)

        return {
            "image": img,
            "mask": mask,
            "box_prompt": box,
            "class_label": sample["class_label"],
            "source_dataset": self.dataset_name,
            "meta": sample.get("meta", {}),
        }

    # ── image loading ────────────────────────────────────────────────

    def _load_image(self, path: str) -> torch.Tensor:
        if not os.path.isfile(path):
            raise FileNotFoundError(f"[{self.dataset_name}] Image not found: {path}")
        # cv2 imread returns BGR; convert to RGB
        img_bgr = cv2.imread(path, cv2.IMREAD_COLOR)
        if img_bgr is None:
            raise ValueError(f"[{self.dataset_name}] Failed to decode: {path}")
        img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
        # Letterbox to target size
        img_rz = _letterbox(img_rgb, self.target_size, interpolation=cv2.INTER_LINEAR)
        # Normalise
        tensor = self.to_tensor(img_rz)  # [0, 1] float32
        tensor = self.normalize(tensor)  # ImageNet stats
        if self.transform is not None:
            tensor = self.transform(tensor)
        return tensor

    def _load_mask(self, sample: dict) -> torch.Tensor:
        """Dispatch to the correct parser based on dataset."""
        path = sample.get("mask_path")
        if path is not None and os.path.isfile(path):
            return parse_png_mask(path, self.target_size)

        # Fallback: inline mask data stored in meta
        meta = sample.get("meta", {})
        if self.dataset_name == "severstal":
            return parse_rle_mask(
                meta.get("rle", ""),
                meta.get("img_h", 256),
                meta.get("img_w", 1600),
                self.target_size,
            )
        if self.dataset_name == "neu_det":
            return parse_bbox_mask(
                meta["bbox"],
                meta.get("img_h", 200),
                meta.get("img_w", 200),
                self.target_size,
            )
        if self.dataset_name == "dagm2007":
            return parse_ellipse_mask(path, self.target_size)

        raise ValueError(
            f"[{self.dataset_name}] No mask available for sample at index "
            f"'{sample.get('image_path', '?')}'"
        )

    # ── split filtering ──────────────────────────────────────────────

    def _filter_split(self, samples: List[dict], split: str) -> List[dict]:
        return [s for s in samples if s.get("split", split) == split]

    # ===================================================================
    # 5. DATASET-SPECIFIC LOADERS
    # ===================================================================

    # ── MVTec AD ──────────────────────────────────────────────────────

    def _load_mvtec_ad(self) -> List[dict]:
        base = os.path.join(self._root_dir, "MVTec AD")
        samples = []

        categories = sorted(
            [d for d in os.listdir(base) if os.path.isdir(os.path.join(base, d))]
        )

        for cat_idx, cat in enumerate(categories):
            gt_dir = os.path.join(base, cat, "ground_truth")
            test_dir = os.path.join(base, cat, "test")
            if not os.path.isdir(gt_dir) or not os.path.isdir(test_dir):
                continue

            defect_types = sorted(
                [
                    d
                    for d in os.listdir(test_dir)
                    if os.path.isdir(os.path.join(test_dir, d)) and d != "good"
                ]
            )

            for defect in defect_types:
                img_folder = os.path.join(test_dir, defect)
                mask_folder = os.path.join(gt_dir, defect)
                if not os.path.isdir(mask_folder):
                    logger.warning(
                        "MVTec AD | %s/%s — ground_truth folder missing", cat, defect
                    )
                    continue

                for fname in sorted(os.listdir(img_folder)):
                    if not fname.lower().endswith((".png", ".jpg", ".jpeg")):
                        continue
                    img_path = os.path.join(img_folder, fname)
                    # Mask name convention: same basename + _mask.png
                    base_name = os.path.splitext(fname)[0]
                    mask_name = f"{base_name}_mask.png"
                    mask_path = os.path.join(mask_folder, mask_name)
                    if not os.path.isfile(mask_path):
                        logger.warning("MVTec AD | mask missing: %s", mask_path)
                        continue
                    samples.append(
                        {
                            "image_path": img_path,
                            "mask_path": mask_path,
                            "class_label": cat_idx,
                            "meta": {"category": cat, "defect": defect},
                            "split": "test",  # all labeled data is in the test set
                        }
                    )

        # Since MVTec AD is unsupervised by design, we use its test set as labeled
        # data and split it into train/val/test for supervised fine-tuning.
        train, val, test = build_splits(
            samples,
            "mvtec_ad",
            stratify=True,
        )
        for s in train:
            s["split"] = "train"
        for s in val:
            s["split"] = "val"
        for s in test:
            s["split"] = "test"
        logger.info(
            "MVTec AD | %d categories, %d labeled samples -> split into "
            "train=%d val=%d test=%d",
            len(categories),
            len(samples),
            len(train),
            len(val),
            len(test),
        )
        return samples

    # ── MVTec AD 2 ────────────────────────────────────────────────────

    def _load_mvtec_ad_2(self) -> List[dict]:
        base = os.path.join(self._root_dir, "mvtec_ad_2")
        samples = []

        categories = sorted(
            [
                d
                for d in os.listdir(base)
                if os.path.isdir(os.path.join(base, d))
                and d not in ("license.txt", "readme.txt")
            ]
        )

        for cat_idx, cat in enumerate(categories):
            test_bad = os.path.join(base, cat, "test_public", "bad")
            gt_dir = os.path.join(base, cat, "test_public", "ground_truth", "bad")
            if not os.path.isdir(test_bad) or not os.path.isdir(gt_dir):
                logger.warning(
                    "MVTec AD 2 | %s — test_public/bad or ground_truth missing", cat
                )
                continue

            for fname in sorted(os.listdir(test_bad)):
                if not fname.lower().endswith((".png", ".jpg", ".jpeg")):
                    continue
                img_path = os.path.join(test_bad, fname)
                base_name = os.path.splitext(fname)[0]
                mask_name = f"{base_name}_mask.png"
