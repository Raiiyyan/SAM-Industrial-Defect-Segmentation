def parse_png_mask(
    path: str, target_size: Tuple[int, int] = TARGET_SIZE
) -> torch.Tensor:
    """Read a binary PNG mask and return a float tensor.

    Input format
    ------------
    Standard PNG image file where foreground (defect) pixels have any
    non-zero value.  Typical sources: MVTec AD, MVTec AD 2, DefectSpectrum.

    Parameters
    ----------
    path : str
        Absolute path to the PNG file.
    target_size : (W, H)
        Output spatial size.  Aspect-ratio-preserving letterbox is applied.

    Returns
    -------
    torch.Tensor  shape (1, H, W), dtype float32, values in {0.0, 1.0}.
    """
    if not os.path.isfile(path):
        raise FileNotFoundError(f"[parse_png_mask] Mask file not found: {path}")

    mask = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
    if mask is None:
        raise ValueError(f"[parse_png_mask] Failed to decode image: {path}")

    # Binarize: any non-zero → 1
    mask = (mask > 0).astype(np.uint8)
    mask = _letterbox(mask, target_size, interpolation=cv2.INTER_NEAREST)
    return torch.from_numpy(mask).unsqueeze(0).float()


def parse_rle_mask(
    rle_string: str, height: int, width: int, target_size: Tuple[int, int] = TARGET_SIZE
) -> torch.Tensor:
    """Decode a Severstal-format Run-Length Encoding string into a binary mask.

    Input format
    ------------
    ``"<start_1> <length_1> <start_2> <length_2> ..."``  where each *start* is a
    1-indexed pixel position in row-major order.  An empty string or whitespace-only
    value means "no defect for this class on this image".

    Parameters
    ----------
    rle_string : str
        The encoded pixel string from the CSV.
    height, width : int
        Original image dimensions (needed because RLE is flat).
    target_size : (W, H)
        Desired output size (letterboxed).

    Returns
    -------
    torch.Tensor  shape (1, H, W), float32, values in {0.0, 1.0}.
    """
    mask = np.zeros(height * width, dtype=np.uint8)

    if rle_string is None or not rle_string.strip():
        # No defect — return all-zero mask
        return torch.zeros((1, target_size[1], target_size[0]), dtype=torch.float32)

    try:
        parts = list(map(int, rle_string.strip().split()))
        if len(parts) % 2 != 0:
            raise ValueError(f"RLE has odd number of tokens ({len(parts)})")
        for i in range(0, len(parts), 2):
            start = parts[i] - 1  # convert to 0-indexed
            length = parts[i + 1]
            mask[start : start + length] = 1
    except Exception as exc:
        raise ValueError(
            f"[parse_rle_mask] Malformed RLE string ({exc}): {rle_string[:200]}..."
        ) from exc

    mask = mask.reshape(height, width)
    mask = _letterbox(mask, target_size, interpolation=cv2.INTER_NEAREST)
    return torch.from_numpy(mask).unsqueeze(0).float()


def parse_ellipse_mask(
    label_path: str, target_size: Tuple[int, int] = TARGET_SIZE
) -> torch.Tensor:
    """Parse a DAGM2007 _label.PNG into a binary mask.

    NOTE
    ----
    DAGM2007 labels are **coarse elliptical region annotations**, not pixel-precise
    ground-truth boundaries.  They were generated by placing a synthetic elliptical
    defect pattern on a textured background.  The label image marks the approximate
    extent of the defect.  **This is a weak / approximate label** — do NOT treat it as
    equally precise to hand-drawn pixel masks (e.g. MVTec AD).
    Downstream evaluation and reporting should account for this lower precision.

    Input format
    ------------
    Grayscale PNG where foreground (ellipse interior) pixels have value 255.
    Background pixels are 0.

    Parameters
    ----------
    label_path : str
        Path to the ``*_label.PNG`` file.
    target_size : (W, H)
        Output spatial size.

    Returns
    -------
    torch.Tensor  shape (1, H, W), float32, values in {0.0, 1.0}.
    """
    if not os.path.isfile(label_path):
        raise FileNotFoundError(
            f"[parse_ellipse_mask] Label file not found: {label_path}"
        )

    mask = cv2.imread(label_path, cv2.IMREAD_GRAYSCALE)
    if mask is None:
        raise ValueError(f"[parse_ellipse_mask] Failed to decode label: {label_path}")

    mask = (mask > 0).astype(np.uint8)
    mask = _letterbox(mask, target_size, interpolation=cv2.INTER_NEAREST)
    return torch.from_numpy(mask).unsqueeze(0).float()


def parse_bbox_mask(
    bbox: Tuple[int, int, int, int],
    height: int,
    width: int,
    target_size: Tuple[int, int] = TARGET_SIZE,
) -> torch.Tensor:
    """Convert a bounding box to a binary mask.

    NOTE
    ----
    NEU Surface Defect ships **bounding-box annotations**, not pixel-precise masks.
    Converting a box to a "mask" means every pixel inside the axis-aligned rectangle
    is treated as defect (value 1).  This is inherently coarser than pixel-wise
    labels and may include substantial background.

    Parameters
    ----------
    bbox : (xmin, ymin, xmax, ymax)  integer pixel coordinates (0-indexed, inclusive).
    height, width : int
        Original image dimensions.
    target_size : (W, H)
        Output spatial size.

    Returns
    -------
    torch.Tensor  shape (1, H, W), float32, values in {0.0, 1.0}.
    """
    x1, y1, x2, y2 = bbox
    # Clamp to image bounds
    x1 = max(0, x1)
    y1 = max(0, y1)
    x2 = min(width - 1, x2)
    y2 = min(height - 1, y2)

    mask = np.zeros((height, width), dtype=np.uint8)
    mask[y1 : y2 + 1, x1 : x2 + 1] = 1

    mask = _letterbox(mask, target_size, interpolation=cv2.INTER_NEAREST)
    return torch.from_numpy(mask).unsqueeze(0).float()


# ===================================================================
# 1b. HELPER: letterbox resize
# ===================================================================


def _letterbox(
    arr: np.ndarray, target_size: Tuple[int, int], interpolation: int = cv2.INTER_LINEAR
) -> np.ndarray:
    """Resize *arr* to *target_size* while preserving aspect ratio (letterbox).

    Parameters
    ----------
    arr : np.ndarray  (H, W) or (H, W, C) uint8.
    target_size : (W, H)  desired output spatial size.
    interpolation : cv2 interpolation flag.

    Returns
    -------
    np.ndarray  shape (target_H, target_W) or (target_H, target_W, C).

    Rationale for letterboxing (vs. stretching)
    -------------------------------------------
    Industrial defect images come from very different camera setups and aspect
    ratios (e.g. Severstal: 1600×256 panoramic; NEU: 200×200 square).  Stretching
    to a common size would distort defect morphology (a circular pit becomes an
    ellipse), which harms both the SAM prompt encoder and the mask decoder.
    Letterboxing preserves geometry at the cost of introducing padded border
    regions — the mask decoder can learn to ignore these because the padded area
    is always zero.
    """
    h, w = arr.shape[:2]
    target_w, target_h = target_size

    scale = min(target_w / w, target_h / h)
    new_w = int(round(w * scale))
    new_h = int(round(h * scale))

    resized = cv2.resize(arr, (new_w, new_h), interpolation=interpolation)

    # Create canvas and paste
    if arr.ndim == 2:
        canvas = np.zeros((target_h, target_w), dtype=arr.dtype)
        y_off = (target_h - new_h) // 2
        x_off = (target_w - new_w) // 2
        canvas[y_off : y_off + new_h, x_off : x_off + new_w] = resized
    else:
        canvas = np.zeros((target_h, target_w, arr.shape[2]), dtype=arr.dtype)
        y_off = (target_h - new_h) // 2
        x_off = (target_w - new_w) // 2
        canvas[y_off : y_off + new_h, x_off : x_off + new_w] = resized

    return canvas


