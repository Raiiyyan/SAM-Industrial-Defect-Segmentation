    def _load_neu_det(self) -> List[dict]:
        base = os.path.join(self._root_dir, "NEU-DET")
        samples = []

        NEU_CLASS_MAP = {
            "crazing": 0,
            "inclusion": 1,
            "patches": 2,
            "pitted_surface": 3,
            "rolled-in_scale": 4,
            "scratches": 5,
        }

        for split_dir in ("train", "validation"):
            ann_dir = os.path.join(base, split_dir, "annotations")
            if not os.path.isdir(ann_dir):
                logger.warning("NEU-DET | annotations dir missing: %s", ann_dir)
                continue

            for xml_file in sorted(glob.glob(os.path.join(ann_dir, "*.xml"))):
                tree = ET.parse(xml_file)
                root = tree.getroot()
                filename = root.find("filename").text
                cls_name = root.find(".//object/name").text
                if cls_name not in NEU_CLASS_MAP:
                    logger.warning(
                        "NEU-DET | unknown class '%s' in %s", cls_name, xml_file
                    )
                    continue

                size = root.find("size")
                img_w = int(size.find("width").text)
                img_h = int(size.find("height").text)

                bbox_el = root.find(".//object/bndbox")
                bbox = (
                    int(bbox_el.find("xmin").text),
                    int(bbox_el.find("ymin").text),
                    int(bbox_el.find("xmax").text),
                    int(bbox_el.find("ymax").text),
                )

                img_path = os.path.join(base, split_dir, "images", cls_name, filename)
                if not os.path.isfile(img_path):
                    logger.warning("NEU-DET | image missing: %s", img_path)
                    continue

                samples.append(
                    {
                        "image_path": img_path,
                        "mask_path": None,
                        "class_label": NEU_CLASS_MAP[cls_name],
                        "meta": {
                            "bbox": bbox,
                            "img_h": img_h,
                            "img_w": img_w,
                            "class_name": cls_name,
                        },
                        "split": "train" if split_dir == "train" else "val",
                    }
                )

        # Use official train/val splits from folder structure
        logger.info(
            "NEU-DET | %d samples (using official train/val split)",
            len(samples),
        )
        return samples

