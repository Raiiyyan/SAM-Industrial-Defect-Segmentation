_SAMPLE_KEYS = ["image_path", "mask_path", "class_label", "meta"]  # meta is a dict


def build_splits(
    samples: List[dict],
    dataset_name: str,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    stratify: bool = True,
) -> Tuple[List[dict], List[dict], List[dict]]:
    """Partition *samples* into train / val / test lists.

    For **Severstal** and **MVTec AD 2** (and any dataset without official labeled
    splits) this function creates a random 70/15/15 split, stratified by class if
    *stratify* is True.

    For datasets that provide their own official splits (NEU, DAGM, DefectSpectrum
    with pre-defined folds, etc.) this function should NOT be called — instead load
    the pre-defined lists directly via the dataset-specific loader.

    Parameters
    ----------
    samples : list of dict
        Each dict must have at least ``"class_label"`` (int).
    dataset_name : str  (for logging only).
    train_ratio, val_ratio, test_ratio : float  (must sum to 1.0).

    Returns
    -------
    train_samples, val_samples, test_samples
    """
    assert (
        abs((train_ratio + val_ratio + test_ratio) - 1.0) < 1e-6
    ), "Ratios must sum to 1.0"

    rng = np.random.default_rng(seed=42)  # deterministic across runs

    if stratify:
        labels = np.array([s["class_label"] for s in samples])
        unique_classes = np.unique(labels)
        train_idx, val_idx, test_idx = [], [], []

        for cls in unique_classes:
            cls_indices = np.where(labels == cls)[0]
            rng.shuffle(cls_indices)
            n = len(cls_indices)
            n_train = max(1, int(round(n * train_ratio)))
            n_val = max(1, int(round(n * val_ratio)))
            # Ensure we don't exceed available samples
            if n_train + n_val > n:
                n_train = n - n_val if n > n_val else n
                n_val = 0
            n_test = n - n_train - n_val

            train_idx.extend(cls_indices[:n_train].tolist())
            val_idx.extend(cls_indices[n_train : n_train + n_val].tolist())
            test_idx.extend(cls_indices[n_train + n_val :].tolist())

        train_s = [samples[i] for i in train_idx]
        val_s = [samples[i] for i in val_idx]
        test_s = [samples[i] for i in test_idx]
    else:
        idx = list(range(len(samples)))
        rng.shuffle(idx)
        n = len(samples)
        n_train = int(round(n * train_ratio))
        n_val = int(round(n * val_ratio))
        train_s = [samples[i] for i in idx[:n_train]]
        val_s = [samples[i] for i in idx[n_train : n_train + n_val]]
        test_s = [samples[i] for i in idx[n_train + n_val :]]

    logger.info(
        "build_splits | %s | stratify=%s | train=%d val=%d test=%d "
        "(ratios %.2f/%.2f/%.2f)",
        dataset_name,
        stratify,
        len(train_s),
        len(val_s),
        len(test_s),
        train_ratio,
        val_ratio,
        test_ratio,
    )
    return train_s, val_s, test_s


