    # ── Severstal Steel Defect ────────────────────────────────────────

    def _load_severstal(self) -> List[dict]:
        base = os.path.join(self._root_dir, "severstal-steel-defect-detection")
        csv_path = os.path.join(base, "train.csv")
        img_dir = os.path.join(base, "train_images")

        if not os.path.isfile(csv_path):
            raise FileNotFoundError(f"Severstal CSV not found: {csv_path}")
        if not os.path.isdir(img_dir):
            raise FileNotFoundError(f"Severstal image dir not found: {img_dir}")

        # Read RLE annotations
        rows = []
        with open(csv_path, "r") as f:
            reader = csv.DictReader(f)
            for row in reader:
                rows.append(row)

        # Group by ImageId — one image can have multiple ClassId entries
        image_data: Dict[str, dict] = {}
        for row in rows:
            img_id = row["ImageId"]
            cls_id = int(row["ClassId"])
            rle = row["EncodedPixels"].strip() if row["EncodedPixels"] else ""
            if img_id not in image_data:
                image_data[img_id] = {"rle_per_class": {1: "", 2: "", 3: "", 4: ""}}
            image_data[img_id]["rle_per_class"][cls_id] = rle

        samples = []
        for img_id, data in image_data.items():
            img_path = os.path.join(img_dir, img_id)
            if not os.path.isfile(img_path):
                logger.warning("Severstal | image missing: %s", img_path)
                continue

            # Read image to get dimensions
            h = cv2.imread(img_path, cv2.IMREAD_UNCHANGED)
            if h is None:
                logger.warning("Severstal | cannot read: %s", img_path)
                continue
            img_h, img_w = h.shape[:2]

            # Create one sample per class that has a non-empty RLE
            any_defect = False
            for cls_id, rle in data["rle_per_class"].items():
                if not rle:
                    continue
                any_defect = True
                samples.append(
                    {
                        "image_path": img_path,
                        "mask_path": None,
                        "class_label": cls_id - 1,  # 0-indexed
                        "meta": {
                            "rle": rle,
                            "img_h": img_h,
                            "img_w": img_w,
                            "class_id": cls_id,
                        },
                        "split": None,
                    }
                )

            if not any_defect:
                # Image with no defects — include as negative sample
                samples.append(
                    {
                        "image_path": img_path,
                        "mask_path": None,
                        "class_label": 4,  # placeholder (avoids collision with Class 1)
                        "meta": {
                            "rle": "",
                            "img_h": img_h,
                            "img_w": img_w,
                            "class_id": 0,
                        },
                        "split": None,
                    }
                )

        # Custom split (no public test labels)
        train, val, test = build_splits(samples, "severstal", stratify=True)
        for s in train:
            s["split"] = "train"
        for s in val:
            s["split"] = "val"
        for s in test:
            s["split"] = "test"
        logger.info(
            "Severstal | %d samples -> train=%d val=%d test=%d",
            len(samples),
            len(train),
            len(val),
            len(test),
        )
        return samples

