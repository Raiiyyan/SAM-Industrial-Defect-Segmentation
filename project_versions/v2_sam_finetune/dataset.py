IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD = [0.229, 0.224, 0.225]
TARGET_SIZE = (
    512,
    512,
)  # (W, H) — 512px for training; SAM pos_embed will be interpolated


