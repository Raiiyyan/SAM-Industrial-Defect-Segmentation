"""
UniversalIndustrialDataset — Unified PyTorch Dataset for multi-class industrial defect segmentation.

Supported datasets (all paths configurable via root_dir):
  - MVTec AD          (folder-based PNG masks)
  - MVTec AD 2        (folder-based PNG masks, unsupervised design — uses test_public labels)
  - Severstal Steel   (RLE-coded masks in train.csv)
  - NEU Surface Defect (Pascal VOC XML bounding-box annotations)
  - DAGM2007          (elliptical region labels in _label.PNG files)
  - DefectSpectrum    (PNG masks in image/mask sub-folder structure)

All images are resized to TARGET_SIZE (default 512x512) with letterboxing
(preserve aspect ratio, pad with zeros).  Masks are handled analogously.

Use precompute_cache() to load all data into RAM before training — critical
for GPU utilization.
"""

